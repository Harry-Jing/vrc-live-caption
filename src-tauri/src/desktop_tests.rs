#[test]
#[expect(
    deprecated,
    reason = "Tauri's mock runtime requires one run iteration to execute the production setup hook."
)]
fn desktop_setup_loads_saved_config_before_commands_run() -> AppResult<()> {
    let nonce = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or(Duration::ZERO)
        .as_nanos();
    let identifier = format!(
        "com.vrclivecaption.startup-test-{}-{nonce}",
        std::process::id()
    );
    let mut probe_context = tauri::test::mock_context(tauri::test::noop_assets());
    probe_context
        .config_mut()
        .identifier
        .clone_from(&identifier);
    let probe_app = tauri::test::mock_builder()
        .build(probe_context)
        .map_err(|error| AppError::runtime(format!("Failed to build path probe: {error}")))?;
    let config_directory = probe_app
        .path()
        .app_config_dir()
        .map_err(|error| AppError::config_io(format!("Failed to resolve test path: {error}")))?;
    drop(probe_app);

    let mut saved_config = AppConfig::default();
    saved_config.audio.input_device_id = Some("saved-device".to_string());
    saved_config.osc.enabled = false;
    fs::create_dir_all(&config_directory).map_err(|error| {
        AppError::config_io(format!("Failed to create test config directory: {error}"))
    })?;
    let contents = serde_json::to_string(&saved_config).map_err(|error| {
        AppError::config_io(format!("Failed to serialize test config: {error}"))
    })?;
    fs::write(config_directory.join("config.json"), contents)
        .map_err(|error| AppError::config_io(format!("Failed to write test config: {error}")))?;

    let mut context = tauri::test::mock_context(tauri::test::noop_assets());
    context.config_mut().identifier = identifier;
    let mut app = manage_state(tauri::test::mock_builder())
        .build(context)
        .map_err(|error| AppError::runtime(format!("Failed to build test app: {error}")))?;
    app.run_iteration(|_, _| {});
    let loaded_config = app
        .state::<AppState>()
        .runtime_control_snapshot()?
        .desired
        .config;
    let persisted_contents = fs::read_to_string(config_directory.join("config.json"))
        .map_err(|error| AppError::config_io(format!("Failed to read test config: {error}")))?;
    let persisted_config = serde_json::from_str::<serde_json::Value>(&persisted_contents)
        .map_err(|error| AppError::config_io(format!("Failed to parse test config: {error}")))?;
    drop(app);

    fs::remove_dir_all(&config_directory).map_err(|error| {
        AppError::config_io(format!("Failed to remove test config directory: {error}"))
    })?;

    assert_eq!(
        loaded_config.audio.input_device_id.as_deref(),
        Some("saved-device")
    );
    assert!(!loaded_config.osc.enabled);
    assert_eq!(
        persisted_config.pointer("/schemaVersion"),
        Some(&serde_json::json!(crate::config::APP_CONFIG_SCHEMA_VERSION))
    );

    Ok(())
}

#[test]
fn exit_event_stops_the_managed_runtime() -> AppResult<()> {
    let app = manage_state(tauri::test::mock_builder())
        .build(tauri::test::mock_context(tauri::test::noop_assets()))
        .map_err(|error| AppError::runtime(format!("Failed to build test app: {error}")))?;

    handle_run_event(app.handle(), tauri::RunEvent::Exit);

    let snapshot = app.state::<AppState>().runtime_control_snapshot()?;
    assert_eq!(snapshot.runtime_status.status, RuntimeStatus::Stopped);
    Ok(())
}
