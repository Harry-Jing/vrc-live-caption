fn production_desktop_source() -> &'static str {
    include_str!("desktop.rs")
        .split("#[path = \"desktop_tests.rs\"]")
        .next()
        .unwrap_or_default()
}

fn registered_tauri_commands() -> AppResult<Vec<String>> {
    let handler = production_desktop_source()
        .split_once("tauri::generate_handler![")
        .and_then(|(_, remainder)| remainder.split_once(']'))
        .map(|(handler, _)| handler)
        .ok_or_else(|| AppError::state("Tauri invoke handler must remain discoverable"))?;

    Ok(handler
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .map(|command| command.trim_end_matches(',').to_string())
        .collect())
}

fn build_manifest_commands() -> AppResult<Vec<String>> {
    let manifest = include_str!("../build.rs")
        .split_once("const APP_COMMANDS: &[&str] = &[")
        .and_then(|(_, remainder)| remainder.split_once("];"))
        .map(|(commands, _)| commands)
        .ok_or_else(|| AppError::state("Tauri build command manifest must remain discoverable"))?;

    Ok(manifest
        .lines()
        .filter_map(|line| {
            line.trim()
                .strip_prefix('"')
                .and_then(|command| command.strip_suffix("\","))
                .map(str::to_owned)
        })
        .collect())
}

#[test]
fn tauri_command_names_match_the_shared_contract() -> AppResult<()> {
    let manifest_json = include_str!("../../contracts/tauri-ipc.json");
    let manifest = serde_json::from_str::<serde_json::Value>(manifest_json).map_err(|error| {
        AppError::config(format!("Failed to parse Tauri IPC contract: {error}"))
    })?;
    let mut expected_commands = manifest
        .get("commands")
        .and_then(serde_json::Value::as_object)
        .ok_or_else(|| AppError::config("Tauri IPC contract must define command names"))?
        .values()
        .map(|value| {
            value
                .as_str()
                .map(str::to_owned)
                .ok_or_else(|| AppError::config("Tauri command names must be strings"))
        })
        .collect::<AppResult<Vec<_>>>()?;
    let mut registered_commands = registered_tauri_commands()?;
    let mut build_commands = build_manifest_commands()?;
    expected_commands.sort();
    registered_commands.sort();
    build_commands.sort();

    assert_eq!(registered_commands, expected_commands);
    assert_eq!(build_commands, expected_commands);
    Ok(())
}

#[test]
fn registered_command_handlers_remain_private_to_the_desktop_shell() -> AppResult<()> {
    let desktop = production_desktop_source();

    for command in registered_tauri_commands()? {
        assert!(desktop.contains(&format!("fn {command}(")));
        for visibility in ["pub fn", "pub(crate) fn", "pub(super) fn"] {
            assert!(
                !desktop.contains(&format!("{visibility} {command}(")),
                "registered command leaked outside the desktop shell: {command}"
            );
        }
    }

    Ok(())
}

#[test]
fn runtime_control_snapshot_is_the_only_control_read_command_exposed() {
    let desktop = production_desktop_source();
    let build_manifest = include_str!("../build.rs");
    let desktop_capability = include_str!("../capabilities/default.json");

    assert!(desktop.contains("get_runtime_control_snapshot,"));
    assert!(build_manifest.contains("\"get_runtime_control_snapshot\""));
    assert!(desktop_capability.contains("\"allow-get-runtime-control-snapshot\""));

    for (command, permission) in [
        ("get_app_config", "allow-get-app-config"),
        ("get_runtime_status", "allow-get-runtime-status"),
        ("get_credential_status", "allow-get-credential-status"),
    ] {
        assert!(!desktop.contains(&format!("fn {command}(")));
        assert!(!build_manifest.contains(&format!("\"{command}\"")));
        assert!(!desktop_capability.contains(&format!("\"{permission}\"")));
    }
}

